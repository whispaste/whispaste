let currentLang = 'en';

/** Apply translations to all data-i18n elements */
function applyTranslations() {
  const t = translations[currentLang];
  if (!t) return;
  document.documentElement.lang = currentLang;

  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    if (t[key] != null) el.textContent = t[key];
  });
  // Restore dynamic connectivity label after translation sweep
  if (typeof updateConnectivityChip === 'function') updateConnectivityChip();
  document.querySelectorAll('[data-i18n-opt]').forEach(el => {
    const key = el.getAttribute('data-i18n-opt');
    if (t[key] != null) el.textContent = t[key];
  });
  document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
    const key = el.getAttribute('data-i18n-placeholder');
    if (t[key] != null) el.placeholder = t[key];
  });
  document.querySelectorAll('[data-i18n-tooltip]').forEach(el => {
    const key = el.getAttribute('data-i18n-tooltip');
    if (t[key] != null) el.setAttribute('data-tooltip', t[key]);
  });
  document.querySelectorAll('[data-i18n-title]').forEach(el => {
    const key = el.getAttribute('data-i18n-title');
    if (t[key] != null) el.title = t[key];
  });
}

/** Set UI language */
function setLang(lang) {
  currentLang = lang;
  applyTranslations();
}

/** Get translation value by key */
function t(key) {
  return (translations[currentLang] || {})[key] || key;
}
