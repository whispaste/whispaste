// Guard: every folder that holds tests is assigned to a run (#1431).
//
// `tool/test_folders.json` lists, per test folder (prefix match, longest wins),
// the run that executes it: a workflow or doc `file` that must contain the
// `needle` naming the command, so renaming the step or dropping the folder from
// the run turns this check red. Static analysis does not count as a run.
// Usage: dart tool/check_test_folders.dart [<repo root>]; exit 1 on any problem.
import 'dart:convert';
import 'dart:io';

final _testFile = RegExp(
  r'(_test\.(dart|cc|cpp|py|sh)|\.test\.(sh|mjs|ts|js|py)|\.spec\.ts|_assert\.sql)$',
);
// _lab_bundles: generated by tool/test_bundles.dart, gitignored (#1492).
const _skipDirs = {'node_modules', 'build', 'dist', 'coverage', '_lab_bundles'};

/// Directories (repo-relative, `/`-separated) that directly contain a test file.
/// Skipped directories are pruned, never listed (keeps the pre-push run fast
/// even with `node_modules` present).
Set<String> discoverTestFolders(Directory root) {
  final found = <String>{};
  void walk(Directory dir, String rel) {
    for (final entity in dir.listSync(followLinks: false)) {
      final name = entity.uri.pathSegments.lastWhere((s) => s.isNotEmpty);
      if (entity is Directory) {
        if (_skipDirs.contains(name) ||
            (name.startsWith('.') && name != '.githooks') ||
            name == 'ephemeral') {
          continue;
        }
        walk(entity, rel.isEmpty ? name : '$rel/$name');
      } else if (entity is File && _testFile.hasMatch(name)) {
        found.add(rel);
      }
    }
  }

  walk(root, '');
  return found;
}

/// Problems of the assignment; empty means every test folder runs somewhere.
List<String> checkTestFolders(Directory root) {
  final manifest = File('${root.path}/tool/test_folders.json');
  if (!manifest.existsSync()) return ['tool/test_folders.json is missing'];
  final entries = [
    for (final e
        in (jsonDecode(manifest.readAsStringSync())
                as Map<String, Object?>)['entries']!
            as List)
      e as Map<String, Object?>,
  ];
  final problems = <String>[];
  for (final e in entries) {
    final path = e['path']! as String;
    final file = File('${root.path}/${e['file']}');
    if (!Directory('${root.path}/$path').existsSync()) {
      problems.add(
        '$path: assigned, but the folder does not exist (remove the entry)',
      );
    } else if (!file.existsSync() ||
        !file.readAsStringSync().contains(e['needle']! as String)) {
      problems.add(
        '$path: run "${e['run']}" not found, ${e['file']} lacks "${e['needle']}"',
      );
    }
  }
  final paths = [for (final e in entries) e['path']! as String];
  for (final folder in discoverTestFolders(root).toList()..sort()) {
    final covered = paths.any((p) => folder == p || folder.startsWith('$p/'));
    if (!covered) {
      problems.add(
        '$folder: holds tests, but no run is assigned (add it to '
        'tool/test_folders.json with a run, or delete the tests)',
      );
    }
  }
  return problems;
}

void main(List<String> args) {
  final problems = checkTestFolders(Directory(args.isEmpty ? '.' : args.first));
  if (problems.isEmpty) {
    stdout.writeln(
      'test folders: every folder with tests is assigned to a run',
    );
    return;
  }
  stderr.writeln('test folders: ${problems.length} problem(s)');
  problems.forEach(stderr.writeln);
  exit(1);
}
