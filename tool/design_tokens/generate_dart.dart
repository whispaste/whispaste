// Design-token build for the desktop app (ADR 0017).
//
//   dart run tool/design_tokens/generate_dart.dart          write the file
//   dart run tool/design_tokens/generate_dart.dart --check  exit 1 if stale
//
// Reads design-tokens/primitives.tokens.json and design-tokens/app.tokens.json
// (DTCG shape, aliases written as {group.token}) and writes
// lib/core/theme/generated/wp_tokens.g.dart. The website keeps its own
// emitter (website/scripts/build-tokens.mjs); both read the same primitives.
import 'dart:convert';
import 'dart:io';

const String kGeneratedPath = 'lib/core/theme/generated/wp_tokens.g.dart';

/// Builds the Dart source from the token directory. Pure apart from reading
/// the two JSON files, so the guard test can compare it with the file on disk.
String generateDartTokens(Directory tokenDir) {
  final primitives = _flatten(_readJson(tokenDir, 'primitives.tokens.json'));
  final app = _flatten(_readJson(tokenDir, 'app.tokens.json'));
  final all = {...primitives, ...app};

  String resolve(String path, [Set<String>? seen]) {
    final token = all[path];
    if (token == null) {
      throw FormatException('Unknown token reference {$path}');
    }
    final value = token.value;
    if (value is String) {
      final alias = RegExp(r'^\{([^}]+)\}$').firstMatch(value);
      if (alias != null) {
        final next = alias.group(1)!;
        final visited = seen ?? <String>{};
        if (!visited.add(next)) {
          throw FormatException('Alias cycle at {$next}');
        }
        return resolve(next, visited);
      }
      return value;
    }
    return jsonEncode(value);
  }

  final out = StringBuffer()
    ..writeln('// GENERATED by tool/design_tokens/generate_dart.dart.')
    ..writeln('// Do not edit. Source: design-tokens/*.tokens.json (ADR 0017).')
    ..writeln('// ignore_for_file: constant_identifier_names')
    ..writeln()
    ..writeln("import 'package:flutter/widgets.dart';")
    ..writeln();

  // Palette primitives.
  out.writeln('/// Raw palette. Components never read these directly; they go');
  out.writeln('/// through a [WpSurfacePalette] role.');
  out.writeln('abstract final class WpPalette {');
  for (final entry in primitives.entries) {
    if (!entry.key.startsWith('color.')) continue;
    final name = _camel(entry.key.substring('color.'.length));
    out.writeln('  static const Color $name = ${_color(resolve(entry.key))};');
  }
  out.writeln('}');
  out.writeln();

  // Surface roles: journal and stage share keys.
  final journalKeys = _keysUnder(app, 'journal');
  final stageKeys = _keysUnder(app, 'stage');
  if (journalKeys.join(',') != stageKeys.join(',')) {
    throw const FormatException('journal and stage must define the same keys');
  }
  out.writeln('/// Colour roles of one surface (journal = light working area,');
  out.writeln(
    '/// stage = navy controls). Both palettes have identical fields.',
  );
  out.writeln('@immutable');
  out.writeln('final class WpSurfacePalette {');
  out.writeln('  const WpSurfacePalette({');
  out.writeln('    required this.brightness,');
  for (final key in journalKeys) {
    out.writeln('    required this.${_camel(key)},');
  }
  out.writeln('  });');
  out.writeln();
  out.writeln('  final Brightness brightness;');
  for (final key in journalKeys) {
    final description = app['journal.$key']!.description;
    if (description != null) out.writeln('  /// $description');
    out.writeln('  final Color ${_camel(key)};');
  }
  out.writeln('}');
  out.writeln();
  for (final surface in const ['journal', 'stage']) {
    final brightness = surface == 'journal' ? 'light' : 'dark';
    out.writeln('const WpSurfacePalette wp${_pascal(surface)}Palette =');
    out.writeln('    WpSurfacePalette(');
    out.writeln('  brightness: Brightness.$brightness,');
    for (final key in journalKeys) {
      out.writeln('  ${_camel(key)}: ${_color(resolve('$surface.$key'))},');
    }
    out.writeln(');');
    out.writeln();
  }

  // Recording overlay and floating button presets (ADR 0024): every
  // overlay.* colour, flat, one constant per token.
  out.writeln('/// Recording overlay and floating-button colours (ADR 0024).');
  _colorClass(out, app, resolve, 'WpOverlayTokens', 'overlay.');
  out.writeln();

  // Coffee support button (Kaffee-Gelb): every coffee.* colour.
  out.writeln('/// Coffee support button colours (Kaffee-Gelb).');
  _colorClass(out, app, resolve, 'WpCoffeeTokens', 'coffee.');
  // First-run onboarding stage ground (Onboarding v6, V12): onboarding.* colours.
  _colorClass(out, app, resolve, 'WpOnboardingTokens', 'onboarding.');
  out.writeln();

  // Scales.
  void scale(String className, String doc, Map<String, String> values) {
    out.writeln('/// $doc');
    out.writeln('abstract final class $className {');
    values.forEach((name, value) {
      out.writeln('  static const double $name = $value;');
    });
    out.writeln('}');
    out.writeln();
  }

  Map<String, String> dims(Map<String, _Token> source, String prefix) => {
    for (final e in source.entries)
      if (e.key.startsWith('$prefix.'))
        _identifier(e.key.substring(prefix.length + 1), prefix): _px(
          resolve(e.key),
        ),
  };

  scale(
    'WpRadiusTokens',
    'Corner radii.',
    dims(primitives, 'radius')..updateAll((k, v) => k == 'pill' ? '999' : v),
  );
  scale('WpShellTokens', 'Desktop shell geometry.', dims(app, 'shell'));
  scale('WpTypeScaleTokens', 'App type scale (logical px).', dims(app, 'type'));
  scale('WpDockTokens', 'Recording dock geometry (WP-79).', dims(app, 'dock'));

  return out.toString();
}

Future<void> main(List<String> args) async {
  final root = Directory.current;
  final formatted = await buildFormattedTokens(
    Directory('${root.path}/design-tokens'),
  );
  final target = File('${root.path}/$kGeneratedPath');
  if (args.contains('--check')) {
    final current = target.existsSync() ? target.readAsStringSync() : '';
    if (current != formatted) {
      stderr.writeln('$kGeneratedPath is stale; run the generator.');
      exitCode = 1;
    }
    return;
  }
  target.parent.createSync(recursive: true);
  target.writeAsStringSync(formatted);
  stdout.writeln('wrote $kGeneratedPath');
}

/// Generated and formatted source, exactly as it is written to disk.
/// [dartExecutable] must be a `dart` binary; under `flutter test`
/// [Platform.resolvedExecutable] is the test runner, so the guard test passes
/// the SDK's own `dart` (`test/test_helpers/dart_sdk.dart`).
Future<String> buildFormattedTokens(
  Directory tokenDir, {
  String? dartExecutable,
}) => _format(
  generateDartTokens(tokenDir),
  dartExecutable ?? Platform.resolvedExecutable,
);

/// Runs `dart format` over [source] so the checked-in file matches the
/// repo's format gate.
Future<String> _format(String source, String dartExecutable) async {
  final process = await Process.start(dartExecutable, [
    'format',
    '--output=show',
    '--stdin-name=wp_tokens.g.dart',
  ]);
  process.stdin.write(source);
  await process.stdin.close();
  final formatted = await process.stdout.transform(utf8.decoder).join();
  final code = await process.exitCode;
  if (code != 0) throw StateError('dart format failed ($code)');
  return formatted;
}

final class _Token {
  const _Token(this.value, this.description);
  final Object? value;
  final String? description;
}

Map<String, dynamic> _readJson(Directory dir, String name) =>
    jsonDecode(File('${dir.path}/$name').readAsStringSync())
        as Map<String, dynamic>;

Map<String, _Token> _flatten(
  Map<String, dynamic> tree, [
  String prefix = '',
  Map<String, _Token>? out,
]) {
  final result = out ?? <String, _Token>{};
  tree.forEach((key, node) {
    if (key.startsWith(r'$') || node is! Map<String, dynamic>) return;
    final path = prefix.isEmpty ? key : '$prefix.$key';
    if (node.containsKey(r'$value')) {
      result[path] = _Token(node[r'$value'], node[r'$description'] as String?);
    } else {
      _flatten(node, path, result);
    }
  });
  return result;
}

/// Writes `abstract final class [className]` with one const colour per
/// `app` token under [prefix] (e.g. `overlay.`), flat, no nesting.
void _colorClass(
  StringBuffer out,
  Map<String, _Token> app,
  String Function(String) resolve,
  String className,
  String prefix,
) {
  out.writeln('abstract final class $className {');
  for (final key in app.keys) {
    if (!key.startsWith(prefix)) continue;
    final description = app[key]!.description;
    if (description != null) out.writeln('  /// $description');
    out.writeln(
      '  static const Color ${_camel(key)} = ${_color(resolve(key))};',
    );
  }
  out.writeln('}');
}

List<String> _keysUnder(Map<String, _Token> tokens, String group) => [
  for (final key in tokens.keys)
    if (key.startsWith('$group.')) key.substring(group.length + 1),
];

/// `#RRGGBB` or `#RRGGBBAA` (CSS order) → `Color(0xAARRGGBB)`.
String _color(String hex) {
  final h = hex.replaceFirst('#', '').toUpperCase();
  if (h.length == 6) return 'Color(0xFF$h)';
  if (h.length == 8) return 'Color(0x${h.substring(6)}${h.substring(0, 6)})';
  throw FormatException('Not a colour: $hex');
}

String _px(String value) => value.endsWith('px')
    ? _num(num.parse(value.substring(0, value.length - 2)))
    : _num(num.parse(value));

String _num(num n) => n == n.roundToDouble() ? '${n.toInt()}.0' : '$n';

String _camel(String path) {
  final parts = path.split(RegExp(r'[.\-]'));
  return parts.first +
      parts.skip(1).map((p) => p.isEmpty ? p : _pascal(p)).join();
}

/// Identifier for a scale step; steps that start with a digit (`space.4`)
/// get the group name as prefix (`space4`).
String _identifier(String path, String group) {
  final name = _camel(path);
  return RegExp(r'^[0-9]').hasMatch(name) ? '${_camel(group)}$name' : name;
}

String _pascal(String s) => s[0].toUpperCase() + s.substring(1);
