import Cocoa
import FlutterMacOS
import os.log

/// A clipboard content fingerprint -- mirrors Dart's `ClipboardFingerprint`
/// (`clipboard_fingerprint.dart`) exactly: byte length + FNV-1a 64 hash of
/// the UTF-8 bytes. Comparing content instead of predicting a `changeCount`
/// sequence number is required here (see that file's doc comment) because a
/// single Dart write can produce more than one `changeCount` bump and this
/// channel is separate from the platform clipboard channel, so dispatch
/// order between them is not guaranteed.
struct ClipboardFingerprint: Hashable {
  let length: Int
  let hash: Int64
}

/// FNV-1a, 64-bit -- bit-for-bit identical to Dart's `_fnv1a64`
/// (`clipboard_fingerprint.dart`). `&*`/`^=` wrap on overflow the same way
/// Dart's `& mask` does, so the two sides produce the same bit pattern;
/// [Int64] on the wire is just that pattern reinterpreted as signed, which
/// both `StandardMethodCodec` and this reinterpretation preserve losslessly.
func fnv1a64(_ bytes: [UInt8]) -> UInt64 {
  var hash: UInt64 = 0xcbf2_9ce4_8422_2325
  let prime: UInt64 = 0x0000_0100_0000_01b3
  for byte in bytes {
    hash ^= UInt64(byte)
    hash = hash &* prime
  }
  return hash
}

func fingerprintOfText(_ text: String) -> ClipboardFingerprint {
  let bytes = Array(text.utf8)
  return ClipboardFingerprint(length: bytes.count, hash: Int64(bitPattern: fnv1a64(bytes)))
}

/// Runs [read] on the serial [queue] and hands its result to [deliver] on the
/// main thread. Pasteboard reads (`types`, `string(forType:)`) are cross-process
/// calls that stall for seconds when the copying app answers slowly (Sentry
/// "App Hanging", #223); a serial queue keeps the copy order.
func readOffMain<T>(on queue: DispatchQueue, read: @escaping () -> T, deliver: @escaping (T) -> Void) {
  queue.async {
    let value = read()
    DispatchQueue.main.async { deliver(value) }
  }
}

/// Serialises WhisPaste's own access to `NSPasteboard.general` (#1484).
/// `NSPasteboard` is not thread-safe and `NSPasteboard(name: .general)` is the
/// same shared instance, so the history monitor's background read
/// (`readOffMain`, #223) and the paste host's main-thread write/snapshot/restore
/// must never overlap: the type cache mutated under the reader and the app
/// died with `EXC_BREAKPOINT` / `EXC_BAD_ACCESS` right after a paste.
///
/// The background reader waits as long as it needs. The main thread waits at
/// most [mainWait]: a read stuck on a slow foreign app (the #223 hang) must
/// not freeze the UI, so after the bound main proceeds and logs it. The lock
/// is recursive because a gated main path may call another gated path
/// (receipt re-arm writes the receipt again).
enum PasteboardGate {
  private static let lock = NSRecursiveLock()
  private static let mainWait: TimeInterval = 1.0
  private static let logger = OSLog(subsystem: "com.whispaste", category: "PasteboardGate")

  /// Background queue: blocks until the pasteboard is free.
  static func read<T>(_ body: () -> T) -> T {
    lock.lock()
    defer { lock.unlock() }
    return body()
  }

  /// Main thread: bounded wait, then runs [body] either way.
  static func onMain<T>(_ body: () -> T) -> T {
    let locked = lock.lock(before: Date().addingTimeInterval(mainWait))
    if !locked {
      os_log("pasteboard busy for %.1fs — proceeding without the gate",
             log: logger, type: .error, mainWait)
    }
    defer { if locked { lock.unlock() } }
    return body()
  }
}

/// Native mirror of Dart's `SelfWriteSuppressionRegistry` -- same 2s expiry,
/// same consume-on-check semantics (a failed/aborted write that never
/// changes the clipboard leaves the mark to expire on its own instead of
/// eating the user's next genuine copy indefinitely).
final class SelfWriteSuppressionRegistry {
  private var pending: [ClipboardFingerprint: Date] = [:]
  private let expiry: TimeInterval = 2.0

  func markSelfWrite(_ fingerprint: ClipboardFingerprint) {
    pending[fingerprint] = Date().addingTimeInterval(expiry)
  }

  func shouldSuppress(_ fingerprint: ClipboardFingerprint) -> Bool {
    guard let expiresAt = pending.removeValue(forKey: fingerprint) else { return false }
    return Date() < expiresAt
  }
}

/// Native macOS clipboard-history monitor (issue 04). Polls
/// `NSPasteboard.general.changeCount` and reports each new text/image entry
/// to Dart's `ClipboardHistoryMonitorService` over `com.whispaste.clipboard_history`
/// -- the same channel `MethodChannelSelfWriteSignal` invokes `markSelfWrite`
/// on (Dart -> native), so this host only *receives* that method, never
/// invokes it.
///
/// Privacy exclusion (`org.nspasteboard.{Transient,Concealed,AutoGenerated}Type`)
/// is reported as flags on every entry -- the drop decision is Dart-core
/// (`shouldExcludeForPrivacy`, issue 01), per PRD.md. Flagged items are
/// additionally not read at all here (see `pollPasteboard`).
class ClipboardMonitorHost {
  private static let pollInterval: TimeInterval = 0.1
  private static let logger = OSLog(subsystem: "com.whispaste", category: "ClipboardMonitorHost")

  private static let transientType = NSPasteboard.PasteboardType("org.nspasteboard.TransientType")
  private static let concealedType = NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType")
  private static let autoGeneratedType = NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType")

  private let channel: FlutterMethodChannel
  private static let readQueue = DispatchQueue(label: "com.whispaste.clipboard-read", qos: .utility)
  private let registry = SelfWriteSuppressionRegistry()
  private var timer: Timer?
  private var lastChangeCount: Int
  // Frontmost-app tracking for the copy source (issue #616). A copy is
  // noticed at most one poll after it happened; if the frontmost app changed
  // within that window, the copy came from the app that was in front before
  // the switch (copy, then Cmd-Tab), not from the one in front now.
  private var frontmostId: String?
  private var previousFrontmostId: String?
  private var frontmostSince: TimeInterval = 0
  private var lastPollAt: TimeInterval = 0
  private var activationObserver: NSObjectProtocol?

  init(messenger: FlutterBinaryMessenger) {
    channel = FlutterMethodChannel(name: "com.whispaste.clipboard_history", binaryMessenger: messenger)
    lastChangeCount = NSPasteboard.general.changeCount
    frontmostId = NSWorkspace.shared.frontmostApplication?.bundleIdentifier
    activationObserver = NSWorkspace.shared.notificationCenter.addObserver(
      forName: NSWorkspace.didActivateApplicationNotification, object: nil, queue: .main
    ) { [weak self] note in
      guard let self else { return }
      let app = note.userInfo?[NSWorkspace.applicationUserInfoKey] as? NSRunningApplication
      guard let id = app?.bundleIdentifier, id != self.frontmostId else { return }
      self.previousFrontmostId = self.frontmostId
      self.frontmostId = id
      self.frontmostSince = ProcessInfo.processInfo.systemUptime
    }
    channel.setMethodCallHandler(handle)
    startPolling()
  }

  private func handle(_ call: FlutterMethodCall, result: @escaping FlutterResult) {
    switch call.method {
    case "markSelfWrite":
      guard let args = call.arguments as? [String: Any],
            let length = args["length"] as? Int,
            let hash = args["hash"] as? Int
      else {
        result(nil)
        return
      }
      registry.markSelfWrite(ClipboardFingerprint(length: length, hash: Int64(hash)))
      result(nil)

    case "listRunningApps":
      // Regular (Dock) apps only; feeds the "pick from running apps" list of
      // the clipboard exclusion setting. Identifier = bundle id.
      let apps = NSWorkspace.shared.runningApplications
        .filter { $0.activationPolicy == .regular }
        .compactMap { app -> [String: String]? in
          guard let id = app.bundleIdentifier else { return nil }
          return ["id": id, "name": app.localizedName ?? id]
        }
      result(apps)

    default:
      result(FlutterMethodNotImplemented)
    }
  }

  private func startPolling() {
    let t = Timer.scheduledTimer(withTimeInterval: Self.pollInterval, repeats: true) { [weak self] _ in
      self?.pollPasteboard()
    }
    RunLoop.main.add(t, forMode: .common)
    timer = t
  }

  private func pollPasteboard() {
    let now = ProcessInfo.processInfo.systemUptime
    let previousPoll = lastPollAt
    lastPollAt = now
    let pb = NSPasteboard.general
    guard pb.changeCount != lastChangeCount else { return }
    lastChangeCount = pb.changeCount
    let sourceApp = copySourceApp(previousPoll: previousPoll)

    // The reads can block on the copying app (promised data), so they run on
    // a background queue; only the cheap changeCount check stays on main (#223).
    // The gate keeps the read off the paste host's main-thread writes (#1484).
    readOffMain(on: Self.readQueue, read: { [weak self] in
      PasteboardGate.read { self?.readEntry(from: pb) }
    }) { [weak self] snapshot in
      guard let self, let snapshot else { return }
      self.handle(snapshot, sourceApp: sourceApp)
    }
  }

  private enum PasteboardSnapshot {
    case text(String, flags: (transient: Bool, concealed: Bool, autoGenerated: Bool))
    case image(Data, flags: (transient: Bool, concealed: Bool, autoGenerated: Bool))
  }

  /// Background queue only: reads the pasteboard, never touches host state.
  private func readEntry(from pb: NSPasteboard) -> PasteboardSnapshot? {
    let types = pb.types ?? []
    let flags: (transient: Bool, concealed: Bool, autoGenerated: Bool) = (
      types.contains(Self.transientType),
      types.contains(Self.concealedType),
      types.contains(Self.autoGeneratedType)
    )

    // Flagged items are dropped by Dart's `shouldExcludeForPrivacy` anyway —
    // don't even read their data. Reading would also resolve the promised
    // data of WhisPaste's own receipt paste (`DesktopPasteHost`) before the
    // target app reads it, defeating the read receipt.
    if flags.transient || flags.concealed || flags.autoGenerated {
      return nil
    }

    if let text = pb.string(forType: .string), !text.isEmpty {
      return .text(text, flags: flags)
    }
    if let imageData = pngData(from: pb) {
      return .image(imageData, flags: flags)
    }
    return nil
  }

  /// Main thread: the self-write registry is main-only.
  private func handle(_ snapshot: PasteboardSnapshot, sourceApp: String?) {
    switch snapshot {
    case let .text(text, flags):
      let fingerprint = fingerprintOfText(text)
      if registry.shouldSuppress(fingerprint) {
        os_log("pollPasteboard: skipped self-write (%d bytes)", log: Self.logger, type: .debug, fingerprint.length)
        return
      }
      emitEntry(kind: "text", text: text, imageData: nil, flags: flags, sourceApp: sourceApp)
    case let .image(data, flags):
      // WhisPaste never writes images to the clipboard itself, so there is
      // no self-write fingerprint scheme for images to check against here.
      emitEntry(kind: "image", text: nil, imageData: data, flags: flags, sourceApp: sourceApp)
    }
  }

  /// The app that most likely made the copy. macOS names no source, so this
  /// is the frontmost app, resolved to the copy moment as far as polling
  /// allows: if it was activated after the previous poll (the copy fell into
  /// the window before that), the app in front before the switch wins.
  /// Residual limit: a copy by a background process, or two switches inside
  /// one 0.1 s poll, cannot be attributed.
  private func copySourceApp(previousPoll: TimeInterval) -> String? {
    if frontmostSince > previousPoll, let previous = previousFrontmostId {
      return previous
    }
    return frontmostId ?? NSWorkspace.shared.frontmostApplication?.bundleIdentifier
  }

  private func pngData(from pasteboard: NSPasteboard) -> Data? {
    guard let image = NSImage(pasteboard: pasteboard),
          let tiff = image.tiffRepresentation,
          let rep = NSBitmapImageRep(data: tiff)
    else {
      return nil
    }
    return rep.representation(using: .png, properties: [:])
  }

  private func emitEntry(
    kind: String,
    text: String?,
    imageData: Data?,
    flags: (transient: Bool, concealed: Bool, autoGenerated: Bool),
    sourceApp: String?
  ) {
    var args: [String: Any] = [
      "kind": kind,
      "capturedAtMs": Int(Date().timeIntervalSince1970 * 1000),
      "transient": flags.transient,
      "concealed": flags.concealed,
      "autoGenerated": flags.autoGenerated,
    ]
    // Used by the per-app exclusion list; see `copySourceApp`.
    if let sourceApp {
      args["sourceApp"] = sourceApp
    }
    if let text {
      args["text"] = text
    }
    if let imageData {
      args["imageBytes"] = FlutterStandardTypedData(bytes: imageData)
    }
    channel.invokeMethod("clipEntryDetected", arguments: args)
  }

  func teardown() {
    timer?.invalidate()
    timer = nil
    if let observer = activationObserver {
      NSWorkspace.shared.notificationCenter.removeObserver(observer)
      activationObserver = nil
    }
    channel.setMethodCallHandler(nil)
  }
}
