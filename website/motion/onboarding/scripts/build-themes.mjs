#!/usr/bin/env node
// Builds themes/<theme>.css from the design tokens. Each composition reads
// only role variables (--stage, --panel, --action, ...); a theme file maps
// those roles onto token values, so a new accent or theme needs a re-render,
// not a composition change. Themes: hell (light journal), dunkel (navy stage),
// marine (navy frame around light content, first-start default).
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { resolve, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const here = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const root = resolve(here, "../../..");
const load = (f) => JSON.parse(readFileSync(resolve(root, "design-tokens", f), "utf8"));
const sources = [load("primitives.tokens.json"), load("app.tokens.json"), load("motion.tokens.json")];

// Resolve a dotted token reference such as "color.navy.900" to its hex value.
function resolveToken(ref) {
  for (const src of sources) {
    let node = src;
    for (const part of ref.split(".")) node = node?.[part];
    if (node && typeof node === "object" && typeof node.$value === "string") return node.$value.toLowerCase();
  }
  throw new Error(`unknown token: ${ref}`);
}

// Resolve a shadow token (array of layers) to a CSS box-shadow value.
function resolveShadow(ref) {
  let node = sources[0];
  for (const part of ref.split(".")) node = node?.[part];
  if (!node || !Array.isArray(node.$value)) throw new Error(`unknown shadow token: ${ref}`);
  return node.$value
    .map((l) => `${l.offsetX} ${l.offsetY} ${l.blur} ${l.spread} ${l.color}`)
    .join(", ");
}

// Role -> token, per theme. Accent note: action (cyan) carries recording and
// action; highlight (amber) is the warm waveform/progress accent only.
const roles = {
  hell: {
    stage: "color.glacier.100", pill: "color.navy.900", screen: "color.navy.900", chip: "color.white",
    panel: "color.white", ink: "color.navy.900", "ink-muted": "color.glacier.700",
    line: "color.glacier.300", "line-strong": "color.glacier.500",
    action: "color.cyan.700", "on-action": "color.white",
    "action-bright": "color.cyan.500", highlight: "color.amber.400",
    "action-on-light": "motion.action-on-light", "accent-on-light": "motion.accent-on-light",
    "action-on-stage": "motion.action-on-light",
    "shadow-lift": "shadow:shadow.light-card",
  },
  dunkel: {
    stage: "color.navy.900", pill: "color.navy.700", screen: "color.navy.950", chip: "color.navy.700",
    panel: "color.navy.800", ink: "color.frost.50", "ink-muted": "color.frost.200",
    line: "color.glacier.700", "line-strong": "color.glacier.500",
    action: "color.cyan.300", "on-action": "color.navy.900",
    "action-bright": "color.cyan.300", highlight: "color.amber.400",
    "action-on-light": "color.cyan.300", "accent-on-light": "color.amber.400",
    "action-on-stage": "color.cyan.300",
    "shadow-lift": "shadow:shadow.panel",
  },
  marine: {
    stage: "overlay.marine.surface", pill: "color.navy.700", screen: "color.navy.950", chip: "color.white",
    panel: "color.glacier.50", ink: "color.navy.900", "ink-muted": "color.glacier.700",
    line: "color.glacier.300", "line-strong": "color.glacier.500",
    action: "color.cyan.700", "on-action": "color.white",
    "action-bright": "color.cyan.500", highlight: "color.amber.400",
    "action-on-light": "motion.action-on-light", "accent-on-light": "motion.accent-on-light",
    "action-on-stage": "color.cyan.500",
    "shadow-lift": "shadow:shadow.panel",
  },
};

const outDir = resolve(here, "themes");
mkdirSync(outDir, { recursive: true });
for (const [theme, map] of Object.entries(roles)) {
  const decls = Object.entries(map)
    .map(([role, ref]) =>
      ref.startsWith("shadow:")
        ? `        --${role}: ${resolveShadow(ref.slice(7))}; /* ${ref.slice(7)} */`
        : `        --${role}: ${resolveToken(ref)}; /* ${ref} */`)
    .join("\n");
  const css = `/* Generated by scripts/build-themes.mjs from design-tokens. Do not edit. */\n` +
    `      :root {\n${decls}\n      }\n`;
  writeFileSync(resolve(outDir, `${theme}.css`), css);
  console.log(`themes/${theme}.css (${Object.keys(map).length} roles)`);
}
