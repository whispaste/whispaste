/// The row a deep link points to: a row id, or a legacy section key.
SettingsSearchEntry? settingsRowAnchorFor(String target) {
  final direct = kSettingsSearchTable.where((r) => r.rowId == target);
  if (direct.isNotEmpty) return direct.first;
  final legacy = kLegacySettingsDeepLinkRowIds[target];
  if (legacy == null) return null;
  return kSettingsSearchTable.firstWhere((r) => r.rowId == legacy);
}

