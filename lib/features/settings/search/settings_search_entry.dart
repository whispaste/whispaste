/// Settings row table and search model (WP-23, spec §3 and §4).
///
/// [kSettingsSearchTable] holds one entry per settings row (84 rows, spec §3):
/// a stable kebab-case [SettingsSearchEntry.rowId], the [SettingsRowArea] that
/// owns it, the ARB label it renders, and synonyms in DE and EN for search.
/// The guard in `test/features/settings/settings_rows_guard_test.dart` keeps
/// the table complete.
library;

import 'package:flutter/widgets.dart';

import '../../../core/l10n/generated/app_localizations.dart';
import '../settings_areas.dart';

/// Resolves one localised settings label from the generated [L10n] strings.
typedef SettingsSearchLabel = String Function(L10n l10n);

/// Where a row belongs: one of the seven settings areas, or a feature page
/// (spec §3, "Umzüge auf Fachseiten"). A feature page that does not exist yet
/// renders its rows inside [SettingsRowArea.hostArea] until it does.
enum SettingsRowArea {
  general,
  appearance,
  shortcuts,
  recording,
  speech,
  textInsert,
  profiles,
  privacy,
  advanced,
  smartMode,
  dictionary,

  /// The About content, the last area of Settings (WP-78).
  about,

  /// Rows that moved to the Help page (the rail's "Hilfe" entry). They are
  /// not part of Settings any more, so they have no settings area to host
  /// them; search opens the Help page instead.
  help;

  /// The settings area that renders the row today, or null for [help], which
  /// lives on a page of its own.
  SettingsArea? get hostArea => switch (this) {
    SettingsRowArea.general => SettingsArea.general,
    SettingsRowArea.appearance => SettingsArea.appearance,
    SettingsRowArea.shortcuts => SettingsArea.shortcuts,
    SettingsRowArea.recording => SettingsArea.recording,
    SettingsRowArea.speech => SettingsArea.speech,
    SettingsRowArea.textInsert => SettingsArea.textInsert,
    SettingsRowArea.profiles => SettingsArea.profiles,
    SettingsRowArea.privacy => SettingsArea.privacy,
    SettingsRowArea.advanced => SettingsArea.advanced,
    // Smart Mode (WP-21) and the dictionary (WP-34) are feature pages that
    // do not exist in this branch yet; their rows stay where they render now.
    SettingsRowArea.smartMode => SettingsArea.textInsert,
    SettingsRowArea.dictionary => SettingsArea.speech,
    SettingsRowArea.about => SettingsArea.about,
    SettingsRowArea.help => null,
  };
}

/// Overline of a search suggestion: the page the row belongs to.
String settingsRowAreaLabel(L10n l10n, SettingsRowArea area) => switch (area) {
  SettingsRowArea.general => l10n.settingsAreaGeneral,
  SettingsRowArea.appearance => l10n.settingsAreaAppearance,
  SettingsRowArea.shortcuts => l10n.settingsAreaShortcuts,
  SettingsRowArea.recording => l10n.settingsAreaRecording,
  SettingsRowArea.speech => l10n.settingsAreaSpeech,
  SettingsRowArea.textInsert => l10n.settingsAreaTextInsert,
  SettingsRowArea.profiles => l10n.settingsAreaProfiles,
  SettingsRowArea.privacy => l10n.settingsAreaPrivacy,
  SettingsRowArea.advanced => l10n.settingsAreaAdvanced,
  SettingsRowArea.smartMode => l10n.settingsAreaSmartMode,
  SettingsRowArea.dictionary => l10n.settingsAreaDictionary,
  SettingsRowArea.about => l10n.pageAboutTitle,
  SettingsRowArea.help => l10n.navHelp,
};

class SettingsSearchEntry {
  const SettingsSearchEntry({
    required this.rowId,
    required this.area,
    required this.labelKey,
    required this.titleOf,
    required this.keywords,
    this.cardKey,
  });

  /// Stable kebab-case id, also the deep-link target and the row's key suffix.
  final String rowId;

  /// Where the row belongs (spec §3).
  final SettingsRowArea area;

  /// ARB key of the row's own label (guard and migration reference).
  final String labelKey;

  /// ARB key of the card heading this row opens, on the first row of a card.
  final String? cardKey;

  /// The row label in the UI language.
  final SettingsSearchLabel titleOf;

  /// Synonyms in DE and EN, searched in every app language.
  final List<String> keywords;

  /// Settings area that renders this row today; null for rows on the Help page.
  SettingsArea? get hostArea => area.hostArea;

  /// Localised title for the given BCP-47 tag; unknown tags fall back to EN.
  String title(String locale) => titleOf(settingsL10nFor(locale));
}

/// Generated strings for a BCP-47 tag; unknown languages fall back to EN.
L10n settingsL10nFor(String locale) {
  final language = locale.split(RegExp('[-_]')).first;
  final supported = L10n.supportedLocales.any(
    (l) => l.languageCode == language,
  );
  return lookupL10n(Locale(supported ? language : 'en'));
}

